"""Extract D01A's fixed city actors with original placement and pose data.
Usage: python tools/extract_city_actors.py path/to/720.zip
Moving traffic/route spawns are separate and are not synthesized here.
"""
from pathlib import Path
import runpy,json,struct
root=Path(__file__).resolve().parents[1]
m=runpy.run_path(str(Path(__file__).with_name('extract_native_maps.py')))
r,w=m['rom'],m['w']
def type_byte(a):return r[0x20000+a-0x6000] if a>=0x6000 else r[0x28000+a-0x4000]
def type_word(a):return type_byte(a)|(type_byte(a+1)<<8)
def object_word(a):return w(0x22000+a-0x6000)
def coordinate(a):return w(0x2a000+a-0x4000)
def signed(n):return n-65536 if n&32768 else n
objects=[]
for address in range(0x20696,0x2072a,4):
 kind=w(address);packed=w(address+2)
 if kind==85:continue # separate crack controller owns these actors
 location=packed&511;bitmap=(object_word(0x7d00+location*2)+(packed>>9)+0x338)&65535
 flags=type_byte(0x6438+kind)
 if not flags&128:raise ValueError('A routed actor requires the route setup path')
 x=(location>>4)*256+(coordinate(0x4ac0+bitmap*2)+signed(type_word(0x62a4+kind*2)))/64
 y=((location&15)+1)*256-(coordinate(0x5580+bitmap*2)+signed(type_word(0x636e+kind*2)))/64
 objects.append({'kind':kind,'packed':packed,'bitmapIndex':bitmap,'actorX':x,'actorY':y,
  'entry':type_word(0x5f7c+kind*2),'rate':type_byte(0x6502+kind),
  'columns':r[0x29c96+kind],'palette':(flags>>4)&3,'stopOnLoop':bool(flags&4)})
data={'source':'D01A/C618-C76C, BE10 dynamic placements, BF5E coordinates, original type tables','objects':objects}
(root/'src/city-actor-data.js').write_text('/** Original fixed city actors; generated by tools/extract_city_actors.py. */\nwindow.Skate720.CITY_ACTOR_DATA='+json.dumps(data,separators=(',',':'))+';\n',encoding='utf-8')
print('Extracted',len(objects),'fixed city actors')
