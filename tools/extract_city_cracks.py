"""Extract the original city crack placements, type85 descriptors and pad impulses.
Uses the same ROM readers as extract_native_maps.py; output is inert data.
"""
from pathlib import Path
import runpy,sys,json,struct
root=Path(__file__).resolve().parents[1]
m=runpy.run_path(str(Path(__file__).with_name('extract_native_maps.py')))
r=m['rom'];w=m['w']
def object_word(a):return struct.unpack_from('<H',r,0x22000+a-0x6000)[0]
def coord_word(a):return struct.unpack_from('<H',r,0x2a000+a-0x4000)[0]
objects=[]
for address in range(0x20696,0x2072a,4):
 kind=w(address);packed=w(address+2)
 if kind!=85:continue
 location=packed&511;cell=(object_word(0x7d00+location*2)+(packed>>9))&65535;bitmap=(cell+0x338)&65535
 # BF5E's low coordinate tables supply offsets inside 256px object cells.
 x=(location>>4)*256+coord_word(0x4ac0+bitmap*2)/64
 y=((location&15)+1)*256-coord_word(0x5580+bitmap*2)/64
 objects.append({'packed':packed,'bitmapIndex':bitmap,'actorX':x,'actorY':y})
data={'source':'D01A city kind85; BE10 dynamic directory; BF5E object cell coordinates; A864-A8B8 launch','kind':85,'entry':w(0x20000+0x5f7c+85*2-0x6000),'columns':r[0x29c96+85],'palette':(r[0x20438+85]>>4)&3,'padImpulses':[w(0x15ca4+i*2) for i in range(4)],'objects':objects}
(root/'src/city-crack-data.js').write_text('/** Original crack data; generated by tools/extract_city_cracks.py. */\nwindow.Skate720.CITY_CRACK_DATA='+json.dumps(data,separators=(',',':'))+';\n',encoding='utf-8')
print('Extracted',len(objects),'original city crack placements')
