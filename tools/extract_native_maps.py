"""Extract inert compressed scenery streams for the native JS map decoder.
Usage: python tools/extract_native_maps.py path/to/720.zip
No instructions or emulator state are included in the output.
"""
from pathlib import Path
import json,struct,base64,zipfile,sys
root=Path(__file__).resolve().parents[1]
with zipfile.ZipFile(sys.argv[1]) as z:
 def chip(n):return z.read(next(x for x in z.namelist() if x.startswith(f'136047-{n}.')))
 rom=bytearray(0x90000)
 for even,odd,offset in [(3126,3127,0x8000),(3128,4131,0x10000),(1129,1132,0x30000),(1130,1133,0x50000)]:
  a,b=chip(even),chip(odd);rom[offset:offset+len(a)*2:2]=a;rom[offset+1:offset+len(b)*2:2]=b
banks=[0x28000,0x20000,0x18000,0x10000,0x2a000,0x22000,0x1a000,0x12000,0x2c000,0x24000,0x1c000,0x14000,0x2e000,0x26000,0x1e000,0x16000,0x48000,0x40000,0x38000,0x30000,0x4a000,0x42000,0x3a000,0x32000,0x4c000,0x44000,0x3c000,0x34000,0x4e000,0x46000,0x3e000,0x36000,0x68000,0x60000,0x58000,0x50000,0x6a000,0x62000,0x5a000,0x52000,0x6c000,0x64000,0x5c000,0x54000,0x6e000,0x66000,0x5e000,0x56000]
def w(a):return struct.unpack_from('<H',rom,a)[0]
def read(base,a):return rom[banks[(base+((a>>3)&0x1c00))>>10]+(a&8191)]
def bw(base,a):return read(base,a)|(read(base,a+1)<<8)
def end_stream(base,ptr,lower):
 cursor=ptr+(read(base,ptr+2) if lower else 0)+3;count=0;mode=0
 for _ in range(128):
  if not count:
   control=read(base,cursor);cursor+=2;count=control&63 or 65536;mode=control>>6
   if mode==2:cursor+=1
  elif mode==0:cursor+=1
  elif mode==2:cursor+=2
  count-=1
 return cursor
source=(root/'src/level-data.js').read_text(encoding='utf-8');levels=json.loads(source.split('window.Skate720.ROM_DATA=',1)[1].strip().rstrip(';'))['levels']
result={'blocks':[],'levels':{},'dynamic':[]};known={}
for kind in range(5):result['dynamic'].append([w(w(0xff54+kind*2)+i*2) for i in range(16)])
for name,info in levels.items():
 kind=['city','slalom','downhill','ramp','jump'].index(info['kind']);variant=0 if kind==0 else int(name.split('-')[1])-1
 offset=0x180 if kind==0 else w(w(0x17f8c+kind*2)-0x6000+0x16000+variant*2)
 cols=info['columns']//16;rows=info['rows']//16;ids=[]
 for i in range(cols*rows):
  ptr=bw(w(0xfeb2+kind*2),offset+i*2)
  if kind==0:base=0x6000 if rom[0x15f16+i//8]&(1<<(i%8)) else 0x4000
  else:base=0xa000 if ptr&1 else w(0xfea2+kind*2)
  key=(base,ptr)
  if key not in known:
   end=max(end_stream(base,ptr,False),end_stream(base,ptr,True));payload=bytes(read(base,a) for a in range(ptr,end))
   known[key]=len(result['blocks']);result['blocks'].append(base64.b64encode(payload).decode())
  ids.append(known[key])
 result['levels'][name]={'kind':kind,'columns':cols,'rows':rows,'blocks':ids,'aliasLow':rom[0xfec2+kind]*1024,'aliasHigh':rom[0xfeca+kind]*1024}
# EC20's city overlays are referenced by bytes immediately before a block.
# FF terminates/pads the reverse list; IDs0..25 have explicit four-byte records.
# Retain all variants so runtime selection need not invent a replacement tile.
overlays=[]
for i in range(48*24):
 ptr=bw(w(0xfeb2),0x180+i*2);base=0x6000 if rom[0x15f16+i//8]&(1<<(i%8)) else 0x4000
 if not read(base,ptr)&128:continue
 for k in range(32):
  entry=read(base,ptr-1-k);index=entry&127
  if index<26:
   selector,group,x,y=[read(0x7800,0x4b58+index*4+j) for j in range(4)]
   height=read(0x7800,0x4bc0+group);width=read(0x7800,0x4bcb+group)
   table=bw(0x7800,0x4be2+group*2);dataBase=0x6000 if read(0x7800,0x4bd6+group) else 0x4000
   # Selector0..3 chooses one of ten classes; other groups have three variants.
   variants=[]
   for variant in range(10 if selector<4 else 3):
    pointer=bw(0x7800,0x4000+table+variant*2)
    variants.append([bw(dataBase,pointer+n*2) for n in range(width*height)])
   overlays.append({'id':index,'selector':selector,'x':(i%48)*16+x,'y':(i//48)*16+y,'width':width,'height':height,'variants':variants})
  if entry&128:break
result['cityOverlays']=overlays
(root/'src/compressed-map-data.js').write_text('/** Original scenery streams only; generated by tools/extract_native_maps.py. */\nwindow.Skate720.COMPRESSED_MAP_DATA='+json.dumps(result,separators=(',',':'))+';\n',encoding='utf-8')
print('Extracted',len(known),'compressed blocks for',len(levels),'layouts')
